//! Build script - discovers all service SQL files in the workspace and
//! generates a Rust module embedding them via `include_str!`.
//!
//! Scans `sentin8/services/*/sql/*.sql` for SQL files. The generated
//! file (`OUT_DIR/service_sql.rs`) contains a `SERVICE_MIGRATIONS` const
//! array of `(display_name, sql_content)` pairs, sorted by service →
//! filename for deterministic ordering.
//!
//! Vertical domains (bank8, hotel8, health8) ship their own SQL via
//! their own CLI/migration tools - sentin8's CLI only handles sentin8
//! platform migrations.

use std::fs;
use std::path::Path;

fn main() {
    // The workspace root is 3 levels up from this crate:
    // sentin8/cmd/cli → sentin8/cmd → sentin8 (workspace root)
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let workspace_root = Path::new(&manifest_dir)
        .ancestors()
        .nth(2) // sentin8/cmd/cli → sentin8/cmd → sentin8
        .unwrap_or(Path::new("."));

    let domains = ["sentin8"];
    let mut entries: Vec<(String, String)> = Vec::new(); // (display, rel_path)

    for domain in &domains {
        // domain is "sentin8" - but workspace_root is already sentin8/,
        // so services are at workspace_root/services/, not workspace_root/sentin8/services/.
        let services_dir = if *domain == "sentin8" {
            workspace_root.join("services")
        } else {
            workspace_root.join(domain).join("services")
        };
        if !services_dir.is_dir() {
            continue;
        }
        let Ok(service_entries) = fs::read_dir(&services_dir) else {
            continue;
        };
        for service_entry in service_entries.flatten() {
            if !service_entry.file_type().is_ok_and(|t| t.is_dir()) {
                continue;
            }
            let service_name = service_entry.file_name().to_string_lossy().to_string();
            let sql_dir = service_entry.path().join("sql");
            if !sql_dir.is_dir() {
                continue;
            }
            let Ok(sql_entries) = fs::read_dir(&sql_dir) else {
                continue;
            };
            for sql_entry in sql_entries.flatten() {
                let path = sql_entry.path();
                if path.extension().is_some_and(|ext| ext == "sql") {
                    let filename = path.file_name().unwrap().to_string_lossy().to_string();
                    let display = format!("{domain}/{service_name}/{filename}");
                    // Relative path from this crate's src/ dir for include_str!
                    let abs = path.canonicalize().unwrap_or(path.clone());
                    entries.push((display, abs.to_string_lossy().to_string()));
                }
            }
        }
    }

    // Sort by (domain, service, priority, filename) for deterministic ordering.
    // Within a service, SQL files must run in dependency order:
    //   1. `init.sql`      - creates the core tables (priority 0)
    //   2. `extended.sql`  - creates additional tables that migrations may
    //                        reference (priority 1)
    //   3. everything else - migrations, seeds, ALTERs (priority 2)
    // Without this, alphabetical sorting would place `async-input.sql`
    // before `extended.sql` (`a` < `e`) and fail on a fresh DB.
    fn sort_key(display: &str) -> (String, String, u8, String) {
        // display = "domain/service/filename" - split into components.
        let parts: Vec<&str> = display.splitn(3, '/').collect();
        let domain = parts.first().copied().unwrap_or("");
        let service = parts.get(1).copied().unwrap_or("");
        let filename = parts.get(2).copied().unwrap_or("");
        let priority = match filename {
            "init.sql" => 0,
            "extended.sql" => 1,
            _ => 2,
        };
        (
            domain.to_string(),
            service.to_string(),
            priority,
            filename.to_string(),
        )
    }
    entries.sort_by_key(|a| sort_key(&a.0));

    // Generate the Rust file.
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let dest = Path::new(&out_dir).join("service_sql.rs");

    let mut code = String::new();
    code.push_str("/// Service SQL files, discovered at build time from all\n");
    code.push_str("/// `*/services/*/sql/*.sql` files in the workspace.\n");
    code.push_str("/// Generated by `build.rs` - do not edit manually.\n");
    code.push_str("pub const SERVICE_MIGRATIONS: &[(&str, &str)] = &[\n");
    for (display, path) in &entries {
        // Use a raw string for the path to handle Windows backslashes.
        code.push_str(&format!("    ({display:?}, include_str!({path:?})),\n"));
    }
    code.push_str("];\n");

    fs::write(&dest, code).expect("failed to write service_sql.rs");

    // Tell Cargo to re-run if any SQL file changes.
    for (_display, path) in &entries {
        println!("cargo:rerun-if-changed={path}");
    }
}
